'''


In Python, // is the floor division operator

Unlike normal division

/

which returns a decimal number (a float), 



// 

floor division divides the numbers and rounds down to the nearest whole integer.

'''


print(5/2) # This will return 2.5, because 5 divided by 2 is 2.5.

print(5//2) # This will return 2, because 5 divided by 2 is 2.5, and the floor division operator rounds it down to 2.











